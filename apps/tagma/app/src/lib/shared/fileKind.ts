const TEST = /\.(test|spec|itest|stest|e2e)\.([a-z0-9]+)$/;

const TEST_BY_EXTENSION: Readonly<Record<string, FileKind>> = {
  ts: 'test-ts',
  mts: 'test-ts',
  cts: 'test-ts',
  js: 'test-js',
  mjs: 'test-js',
  cjs: 'test-js',
  tsx: 'test-jsx',
  jsx: 'test-jsx',
};

export function fileKind(path: string): FileKind {
  const name = path.slice(path.lastIndexOf('/') + 1).toLowerCase();
  const named = BY_NAME[name];
  if (named !== undefined) return named;
  if (name === '.env' || name.startsWith('.env.')) return 'tune';
  if (name.endsWith('.d.ts')) return 'typescript-def';
  const test = TEST.exec(name);
  const tested = test === null ? undefined : TEST_BY_EXTENSION[test[2]!];
  if (tested !== undefined) return tested;
  const dot = name.lastIndexOf('.');
  return dot <= 0 ? 'file' : (BY_EXTENSION[name.slice(dot + 1)] ?? 'file');
}
