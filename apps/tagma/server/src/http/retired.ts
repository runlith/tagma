const gone = (path: string, operation: string) =>
  HttpServerResponse.json(
    {
      code: 'route-retired',
      reason: `${path} no longer answers: the operation ${operation} took its place`,
      unblock: [`POST /api/op/${operation} with the operation's own input`],
    },
    { status: 410 },
  );

const [first, ...rest] = RETIRED.map(([method, path, operation]) => HttpRouter.add(method, path, () => gone(path, operation)));

export const retiredRoutes = first === undefined ? Layer.empty : Layer.mergeAll(first, ...rest);
