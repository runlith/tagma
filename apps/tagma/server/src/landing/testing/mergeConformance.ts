import { expect } from 'bun:test';
import { Effect } from 'effect';
import type { MergeGit } from '../contract/service/mergeGit.js';

export type MergeGitFixture = {
  readonly git: MergeGit['Service'];
  readonly main: string;
  readonly side: string;
  readonly base: string;
  readonly tip: string;
  readonly tree: string;
  readonly write: (path: string, text: string) => Effect.Effect<void>;
  readonly read: (path: string) => Effect.Effect<string>;
  readonly stage: (path: string, text: string) => Effect.Effect<string>;
  readonly interrupt: (sequenced: boolean) => Effect.Effect<void>;
};

export const verifyMergeGit = Effect.fnUntraced(function* (fixture: MergeGitFixture) {
  const { git, main, side, base, tip, tree } = fixture;
  expect(yield* git.head(main)).toEqual({ ref: 'refs/heads/main', commit: base });
  expect(yield* git.resolve(main, 'refs/heads/side')).toBe(tip);
  expect(yield* git.resolve(main, 'refs/heads/missing')).toBeNull();
  expect(yield* git.tree(main, tip)).toBe(tree);
  expect(yield* git.changed(main, base, tip)).toEqual(['feature.txt']);
  expect(yield* git.changed(main, base, tip, true)).toEqual(['feature.txt']);
  expect(yield* git.ancestor(main, tip, base)).toBe(false);
  const merged = yield* git.create(main, { tree, parents: [base, tip], message: 'merge feature', sign: false });
  expect(yield* git.ancestor(main, base, merged)).toBe(true);
  expect(yield* git.ancestor(main, tip, merged)).toBe(true);
  yield* fixture.write('draft.txt', 'unfinished\n');
  const at = { checkout: main, ref: 'refs/heads/main', base, commit: merged };
  expect(yield* git.advance(at, 'publish merge')).toBe(true);
  expect(yield* git.advance({ ...at, commit: tip }, 'stale publication')).toBe(false);
  expect(yield* git.settle(at)).toEqual({ unsynced: [], reason: null });
  expect(yield* fixture.read('feature.txt')).toBe('feature\n');
  expect(yield* fixture.read('draft.txt')).toBe('unfinished\n');
  const repository = yield* git.repository(main);
  expect(yield* git.proved(repository, main, at.ref, merged)).toBe(true);
  expect(yield* git.advance({ ...at, base: merged, commit: base }, 'rewind')).toBe(true);
  expect(yield* git.settle({ ...at, base: merged, commit: base })).toEqual({ unsynced: [], reason: null });
  expect(yield* git.proved(repository, main, at.ref, merged)).toBe(true);
  yield* fixture.write('feature.txt', 'local unfinished work\n');
  expect(yield* git.advance(at, 'publish with dirty checkout')).toBe(true);
  const stopped = yield* git.settle(at);
  expect(stopped.unsynced).toEqual(['feature.txt']);
  expect(stopped.reason).not.toBeNull();
  expect(yield* fixture.read('feature.txt')).toBe('local unfinished work\n');
  expect(yield* git.head(main)).toEqual({ ref: at.ref, commit: merged });
  const indexed = yield* fixture.stage('seed.txt', 'staged target\n');
  yield* fixture.write('seed.txt', 'seed\n');
  const next = yield* git.create(main, { tree: indexed, parents: [merged], message: 'staged target', sign: false });
  const reverted = { ...at, base: merged, commit: next };
  expect(yield* git.advance(reverted, 'preserve unstaged revert')).toBe(true);
  expect(yield* git.settle(reverted)).toEqual({ unsynced: [], reason: null });
  expect(yield* fixture.read('seed.txt')).toBe('seed\n');
  const replayed = yield* git.replay(side, base, tip, false);
  expect(replayed.tree).toBe(tree);
  expect(replayed.conflicts).toEqual([]);
  const taken = yield* git.take({ checkout: side, branch: 'side', baseBranch: 'main', tip, baseTip: merged, tree });
  expect((yield* git.head(side)).commit).toBe(taken);
  expect(yield* git.ancestor(side, merged, taken)).toBe(true);
  expect(yield* git.interrupted(main)).toBeNull();
  yield* fixture.interrupt(false);
  expect(yield* git.interrupted(main)).toEqual({ ref: at.ref, roots: ['side-root'] });
  yield* fixture.interrupt(true);
  expect(yield* git.interrupted(main)).toBeNull();
});
