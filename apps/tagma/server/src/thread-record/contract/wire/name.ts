const pick = <T>(words: readonly T[]): T => words[Math.floor(Math.random() * words.length)] as T;

const PICKS_BEFORE_COUNTING = 64;

export function randomThreadName(taken: ReadonlySet<string> = new Set()): string {
  let name = `${pick(SHADES)}-${pick(CREATURES)}`;
  for (let tries = 1; taken.has(name) && tries < PICKS_BEFORE_COUNTING; tries += 1) {
    name = `${pick(SHADES)}-${pick(CREATURES)}`;
  }
  if (!taken.has(name)) return name;
  let count = 2;
  while (taken.has(`${name}-${count}`)) count += 1;
  return `${name}-${count}`;
}

export const NAME_PROVENANCES = ['generated', 'chosen'] as const;
export type NameProvenance = (typeof NAME_PROVENANCES)[number];

export function forkThreadName(source: string): string {
  return `fork (${source})`;
}
