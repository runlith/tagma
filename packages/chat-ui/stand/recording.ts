export type Rect = { top: number; bottom: number; left: number; right: number; height: number; width: number };
export type RailTarget = { target: string; rect: Rect };
export type Targets = {
  viewport: Rect;
  host: Rect;
  visual: Rect | null;
  scale: number;
  latest: Rect | null;
  composer: Rect | null;
  disclosure: Rect | null;
  rail: RailTarget[];
};
export type Sentinel = { id: number; row: string; rect: Rect; text: string };
export type ImageSignature = { source: number; complete: boolean; width: number; height: number };
export type RowSignature = {
  text: number;
  structure: number;
  images: ImageSignature[];
  anchors: string[];
  expanded: string[];
  font: string;
  fonts: string;
};
export type RowRect = { key: string; rect: Rect; content?: Rect; signature: RowSignature; live: boolean };
export type LayoutBox = {
  id: number;
  parent: number | null;
  tag: string;
  classes: string;
  rect: Rect;
  height: string;
  margin: string;
  padding: string;
  overflow: string;
  animations: { state: string; time: string | null; end: string }[];
};
export type Anchor = { kind: 'paused' | 'following' | 'disclosure'; row: string; rect: Rect };
export type ObservedEntries = {
  readonly jump: string;
  message(key: string): string | null;
  kind(key: string): string;
  tail(key: string): boolean;
};
export type RowChange = {
  key: string;
  kind: string;
  before: number | null;
  after: number;
  beforeWidth: number | null;
  afterWidth: number;
  remount: boolean;
  frame: number;
};
export type Mount = RowChange & { measured: boolean };
export type Frame = {
  time: number;
  sampled: number;
  dpr: number;
  scrollTop: number;
  scrollHeight: number;
  viewport: Rect;
  rows: RowRect[];
  sentinels: Sentinel[];
  blank: number;
  rail: boolean;
  tiles: number;
  gold: string | null;
  geometry: string | null;
  line: number;
  selected: string | null;
  mutation: number;
  sizeChanges: number;
  unmeasured: number;
  moving: boolean;
  touching: boolean;
  finger: number | null;
  structure: boolean;
  control: Rect | null;
  controlRow: string | null;
  controlExpanded: string | null;
  controlAnimating: boolean;
  disclosure?: LayoutBox[];
  anchor: Anchor | null;
  changes: RowChange[];
  mounts: Mount[];
};
export type Drag = { distance: number; speed: number; fromFrame: number; toFrame: number; preventFling: boolean; quantum?: number };
export type WheelStep = { frame: number; deltaY: number; deltaMode: number; stamp: number; received: number };
export type WheelRun = { fromFrame: number; toFrame: number; steps: WheelStep[] };
export type ScrollStep = { stamp: number; received: number; top: number };
export type TrustedTouch = { type: string; timeStamp: number; received: number; x: number | null; y: number | null };
export type Navigation = {
  kind: 'rail' | 'latest' | 'keyboard';
  target: string;
  fromFrame: number;
  toFrame: number | null;
  timeStamp: number;
  received: number;
};
export type Scrollbar = { track: Rect; x: number; gutter: number; viewport: number; range: number; top: number };
export type ThumbSample = { y: number; time: number; top: number };
export type ThumbControl = { scrollbar: Scrollbar; samples: ThumbSample[]; recording: Recording };
export type ThumbReference = { scale: number; interval: number; trial: Scrollbar; control: ThumbControl[] };
export type ScrollWrite = { time: number; frame: number; method: 'scrollTop' | 'scrollTo' | 'scrollBy'; from: number; to: number };
export type Recording = {
  name: string;
  frames: Frame[];
  touches: TrustedTouch[];
  drags: Drag[];
  wheels: WheelRun[];
  writes?: ScrollWrite[];
  scrolls?: ScrollStep[];
  timings?: number[];
  ticks?: number[];
  commands?: Navigation[];
  thumb?: ThumbReference;
};
export type MeasuredControl = { rows: number; frames: number; start: number; from: number; to: number };
